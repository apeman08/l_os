#!/usr/bin/env python3
"""Generate crates/l_core/src/font_data.rs from a Terminus BDF.

Input : ter-u16n.bdf from Terminus Font 4.49.1 (SIL OFL 1.1)
        https://downloads.sourceforge.net/project/terminus-font/terminus-font-4.49/terminus-font-4.49.1.tar.gz
        (inside the tarball: terminus-font-4.49.1/ter-u16n.bdf, checked with `tar tzf`)
Kept codepoints: U+0020-007E, U+00A0-00FF, U+2500-259F (where Terminus has
        them), plus U+2013 2014 2018 2019 201C 201D 2022 2026 20AC and
        U+2190-2193 2713 2717 25CB 25CF 2588.
Format: 16 rows per glyph, one byte per row, MSB (bit 7) = leftmost pixel
        (the BDF native order). Output is sorted by codepoint.
Regenerate:
        python3 -I scripts/gen_font.py path/to/ter-u16n.bdf crates/l_core/src/font_data.rs
"""
import sys

bdf, out = sys.argv[1], sys.argv[2]
want = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x2500, 0x25A0)) | {
    0x20AC, 0x2022, 0x2190, 0x2191, 0x2192, 0x2193, 0x2713, 0x2717, 0x2026,
    0x2018, 0x2019, 0x201C, 0x201D, 0x2013, 0x2014, 0x25CF, 0x25CB, 0x2588}
g = {}
cur = None
inbm = False
for line in open(bdf, encoding='latin-1'):
    t = line.split()
    if not t:
        continue
    if t[0] == 'ENCODING':
        cur = int(t[1])
        rows = []
    elif t[0] == 'BITMAP':
        inbm = True
    elif t[0] == 'ENDCHAR':
        inbm = False
        if cur in want and len(rows) == 16:
            g[cur] = rows
    elif inbm:
        rows.append(int(t[0], 16))
with open(out, 'w') as f:
    f.write("// @generated by scripts/gen_font.py from Terminus Font 4.49.1 ter-u16n.bdf\n// (SIL OFL 1.1, see LICENSE-font). Do not edit by hand. Sorted by codepoint.\n")
    f.write("pub(crate) static GLYPHS: &[(char, [u8; 16])] = &[\n")
    for cp in sorted(g):
        f.write("    ('\\u{%04X}', [%s]),\n" % (cp, ", ".join("0x%02X" % b for b in g[cp])))
    f.write("];\n")
