#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn contrast_black_white_is_21() {
        let c = contrast(Rgb(0, 0, 0), Rgb(255, 255, 255));
        assert!((c - 21.0).abs() < 0.01, "{c}");
    }

    #[test]
    fn contrast_is_symmetric() {
        let a = Rgb(10, 200, 90);
        let b = Rgb(240, 30, 120);
        assert_eq!(contrast(a, b), contrast(b, a));
        assert!((contrast(a, a) - 1.0).abs() < 1e-4);
    }

    #[test]
    fn contrast_known_value() {
        // #777777 on white is the well-known 4.48:1 (just below AA).
        let c = contrast(Rgb(0x77, 0x77, 0x77), Rgb(255, 255, 255));
        assert!((c - 4.48).abs() < 0.02, "{c}");
    }

    #[test]
    fn text_on_bg_at_least_7() {
        assert!(contrast(AURORA.text, AURORA.bg) >= 7.0);
    }

    #[test]
    fn all_other_text_colors_at_least_4_5_on_bg_and_surface() {
        let t = AURORA;
        for (name, c) in [("muted", t.muted), ("accent", t.accent), ("ok", t.ok), ("warn", t.warn), ("err", t.err)] {
            assert!(contrast(c, t.bg) >= 4.5, "{name} on bg: {}", contrast(c, t.bg));
            assert!(contrast(c, t.surface) >= 4.5, "{name} on surface: {}", contrast(c, t.surface));
        }
    }

    #[test]
    fn accent_differs_from_status_colors() {
        let t = AURORA;
        assert_ne!(t.accent, t.ok);
        assert_ne!(t.accent, t.warn);
        assert_ne!(t.accent, t.err);
    }
}
